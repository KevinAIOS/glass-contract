/** The catalog defines vocabulary, not device support or a permission grant. */
export function createCapabilityCatalog(): Capability[] {
  return CapabilityIdSchema.options.map((id) => ({
    id,
    declaration: "unknown",
    validation: "unverified",
    availability: "unknown",
    permissions: [...permissions[id]],
    errors: [...ErrorCodeSchema.options],
  }))
}

export function createManifest(): Manifest {
  const capabilities = createCapabilityCatalog()
  const ids = [...new Set(capabilities.flatMap((c) => c.permissions))]
  return {
    schema_version: 1,
    id: "aios.glass.platform",
    version: "0.1.0",
    capabilities,
    permissions: ids.map((id) => ({id, state: "unknown", scope: "host"})),
  }
}
